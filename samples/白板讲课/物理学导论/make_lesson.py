def T(at, x, y, text, s=36, c="ink", font="zh", align="center"):
    return {"t": "text", "at": at, "x": x, "y": y, "text": text, "s": s, "c": c, "font": font, "align": align}
def I(at, name, x, y, size=200, c="ink", w=3.4):
    return {"t": "icon", "at": at, "name": name, "x": x, "y": y, "size": size, "c": c, "w": w}
def BOX(at, x, y, w, h, zh, en=None, c="ink", s=40):
    return {"t": "box", "at": at, "x": x, "y": y, "w": w, "h": h, "zh": zh, "en": en, "c": c, "s": s}
def A(at, *pts, c="ink", w=3.2):
    return {"t": "arrow", "at": at, "pts": [list(p) for p in pts], "c": c, "w": w}
def LN(at, *pts, c="ink", w=3):
    return {"t": "line", "at": at, "pts": [list(p) for p in pts], "c": c, "w": w}

