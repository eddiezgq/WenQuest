# ---------------------------------------------------------------- 讲义
d = Doc()
d.title("第3章  动量守恒定律和能量守恒定律", "大学物理A（上）课程讲义  ·  2026 秋")
d.p("牛顿第二定律描述力的瞬时效果。把它对时间积累，得到动量定理；对空间积累，得到动能定理。在一定条件下，动量和机械能守恒，这使我们不必知道过程细节就能求出结果。")
d.h("3.1  冲量与动量定理")
d.p("力对时间的积累称为冲量 I = ∫F dt。由 F = dp/dt 得质点动量定理：")
d.eq("I = ∫_{t₁}^{t₂} F dt = p₂ − p₁ = m v₂ − m v₁")
d.p("对质点系，内力成对出现、冲量相互抵消，于是系统所受合外力的冲量等于系统总动量的增量。")
d.h("3.2  动量守恒定律")
d.p("当系统所受合外力为零时，系统总动量保持不变：Σ mᵢ vᵢ = 常矢量。若合外力不为零，但在某一方向上的分量为零，则该方向上的动量守恒。碰撞、爆炸等过程时间极短，内力远大于外力，常可近似认为动量守恒。")
d.image(FIG + "动量守恒-碰撞示意.png", 11, "图3-1  两球对心碰撞")
d.h("3.3  功与动能定理")
d.p("力对空间的积累称为功，W = ∫ F·dr。弹簧从伸长 x₁ 到 x₂ 时弹力做功 W = ½k x₁² − ½k x₂²。合力对质点做的功等于质点动能的增量（动能定理）：")
d.eq("W = ½ m v₂² − ½ m v₁²")
d.h("3.4  保守力、势能与机械能守恒")
d.p("做功只与始末位置有关、与路径无关的力称为保守力，如重力、弹簧弹力和万有引力。对保守力可以定义势能：")
d.table(["保守力", "势能表达式", "势能零点"], [
    ["重力", "E_p = mgh", "任选（通常取地面）"],
    ["弹簧弹力", "E_p = ½ k x²", "弹簧原长处"],
    ["万有引力", "E_p = −G M m / r", "无穷远处"],
], widths=[3.5, 5, 5])
d.p("功能原理：外力和非保守内力做功之和等于系统机械能的增量。当外力和非保守内力都不做功时，系统机械能守恒：E_k + E_p = 常量。")
d.h("3.5  碰撞")
d.p("设质量为 m₁、m₂ 的两球沿一直线碰撞，碰前速度 v₁₀、v₂₀，碰后 v₁、v₂。动量守恒：m₁v₁₀ + m₂v₂₀ = m₁v₁ + m₂v₂。")
d.bullets([
    ("完全弹性碰撞（动能也守恒）：", "v₁ = [(m₁ − m₂)v₁₀ + 2m₂v₂₀]/(m₁ + m₂)，v₂ = [(m₂ − m₁)v₂₀ + 2m₁v₁₀]/(m₁ + m₂)。质量相等时两球交换速度。"),
    ("完全非弹性碰撞（碰后粘在一起）：", "v = (m₁v₁₀ + m₂v₂₀)/(m₁ + m₂)，动能损失最大。"),
])
d.example("【例3-1】（冲击摆）", "质量 m = 10 g 的子弹水平射入悬挂的质量 M = 1.99 kg 的木块并留在其中，木块摆起的最大高度 h = 5.0 cm。求子弹的速度。（g 取 9.8 m/s²）", [
    "碰撞瞬间（时间极短）：水平方向动量守恒，m v₀ = (m + M) V。",
    "摆动过程：只有重力做功，机械能守恒，½(m + M)V² = (m + M) g h，得 V = √(2gh) ≈ 0.99 m/s。",
    "v₀ = (m + M)V / m = 200 × 0.99 ≈ 198 m/s。",
    "讨论：碰撞中动能损失比例为 M/(m + M) ≈ 99.5%，所以碰撞过程不能用机械能守恒。",
])
d.h("本章小结")
d.bullets(["动量定理：合外力的冲量 = 动量增量；动量守恒条件：合外力为零（或某方向分量为零）。",
           "动能定理：合力的功 = 动能增量；机械能守恒条件：外力和非保守内力不做功。",
           "多过程问题分段处理，每段分别判断用哪条守恒定律。"])
