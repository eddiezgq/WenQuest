# ---------------------------------------------------------------- 讲义 (exported to PDF later)
d = Doc()
d.title("第1章  质点运动学", "大学物理A（上）课程讲义  ·  2026 秋")
d.p("运动学研究物体的位置如何随时间变化，而不追究变化的原因。本章建立描述运动的一整套物理量——位置矢量、位移、速度和加速度，并用它们处理抛体运动、圆周运动和相对运动。本章的核心数学工具是矢量和微积分：从运动方程求导得到速度和加速度，从加速度积分（加上初始条件）得到运动方程。")
d.h("1.1  参考系、坐标系与质点")
d.p("描述运动必须先选定参考系，同一运动在不同参考系中看来不同。为了定量描述，还要在参考系上建立坐标系，常用直角坐标系和自然坐标系。当物体的形状和大小对所研究的问题影响可以忽略时，可以把它看成一个有质量的点，称为质点。质点是一种理想模型：地球绕太阳公转时可以看作质点，研究地球自转时则不能。")
d.h("1.2  描述质点运动的物理量")
d.h("1.2.1  位置矢量与运动方程", 3)
d.p("从坐标原点指向质点所在位置的有向线段称为位置矢量（位矢），在直角坐标系中")
d.eq("r = x i + y j + z k")
d.p("质点运动时，位矢随时间变化，r = r(t) 称为运动方程，其分量形式为 x = x(t)、y = y(t)、z = z(t)。从分量式中消去 t，得到轨迹方程。")
d.h("1.2.2  位移与路程", 3)
d.p("质点在 Δt 时间内位矢的增量 Δr = r(t+Δt) − r(t) 称为位移，它是矢量，只与始末位置有关；路程 Δs 是质点实际经过轨迹的长度，是标量。一般情况下 |Δr| ≠ Δs，只有在 Δt → 0 时才有 |dr| = ds。还要注意 |Δr| 与 Δr（位矢大小的增量 Δ|r|）是两个不同的量。")
d.h("1.2.3  速度", 3)
d.p("平均速度 v̄ = Δr/Δt，瞬时速度（简称速度）是平均速度在 Δt → 0 时的极限：")
d.eq("v = dr/dt = (dx/dt) i + (dy/dt) j + (dz/dt) k")
d.p("速度的方向沿轨迹的切线方向，大小称为速率 v = |v| = ds/dt。")
d.h("1.2.4  加速度", 3)
d.eq("a = dv/dt = d²r/dt²,    aₓ = d²x/dt²,  a_y = d²y/dt²,  a_z = d²z/dt²")
d.example("【例1-1】", "质点的运动方程为 r = 2t i + (19 − 2t²) j（SI 单位）。求：(1) 轨迹方程；(2) t = 1 s 时的速度和加速度。", [
    "(1) x = 2t，y = 19 − 2t²，消去 t 得 y = 19 − x²/2，轨迹为抛物线（x ≥ 0）。",
    "(2) v = dr/dt = 2 i − 4t j，t = 1 s 时 v = 2 i − 4 j（m/s），速率 v = √20 ≈ 4.47 m/s。",
    "a = dv/dt = −4 j（m/s²），加速度为恒矢量，方向沿 −y。",
])
d.h("1.2.5  由加速度求运动方程", 3)
d.p("若已知 a(t) 和初始条件 t = 0 时 v = v₀、r = r₀，则")
d.eq("v = v₀ + ∫₀ᵗ a dt,        r = r₀ + ∫₀ᵗ v dt")
d.p("对于直线运动中 a 是速度或位置的函数的情况，可利用 a = dv/dt = v·dv/dx 分离变量后积分。")
d.example("【例1-2】", "汽艇关闭发动机后在水中做减速直线运动，加速度 a = −kv²（k 为常量）。设关机时速度为 v₀，求速度随时间的变化和关机后行驶的距离与速度的关系。", [
    "由 dv/dt = −kv² 分离变量：dv/v² = −k dt，两边积分（t = 0 时 v = v₀）得 1/v − 1/v₀ = kt，即 v = v₀/(1 + v₀kt)。",
    "由 v·dv/dx = −kv² 得 dv/v = −k dx，积分得 ln(v/v₀) = −kx，即 x = (1/k) ln(v₀/v)。",
    "讨论：v → 0 需要 t → ∞，但距离随 v 减小只按对数增长，这与实际观察一致。",
])
d.h("1.3  抛体运动")
d.p("在忽略空气阻力时，抛体只受重力，加速度恒为 a = −g j。以抛出点为原点、初速度 v₀ 与水平方向成 θ 角，积分得运动方程：")
d.eq("x = v₀ cosθ · t,        y = v₀ sinθ · t − ½ g t²")
d.p("消去 t 得轨迹方程 y = x tanθ − g x² / (2 v₀² cos²θ)，是一条抛物线。令 y = 0 得飞行时间 T = 2 v₀ sinθ / g 和射程")
d.eq("R = v₀² sin2θ / g")
d.p("当 θ = 45° 时射程最大，R_max = v₀²/g；互余的两个抛射角（如 30° 与 60°）射程相同。最大高度 H = v₀² sin²θ / (2g)。")
d.image(FIG + "抛体运动轨迹.png", 13.5, "图1-1  不同抛射角的抛体轨迹（v₀ = 20 m/s，g = 9.8 m/s²）")
d.h("1.4  圆周运动")
d.p("在自然坐标系中，速度总沿切向 eₜ：v = v eₜ。对时间求导时，不仅 v 的大小变化，eₜ 的方向也在变化，于是加速度分为两部分：")
d.eq("a = aₜ eₜ + aₙ eₙ,        aₜ = dv/dt,        aₙ = v²/R")
d.p("切向加速度 aₜ 反映速率的变化，法向加速度 aₙ 指向圆心，反映速度方向的变化。匀速圆周运动中 aₜ = 0，但 aₙ ≠ 0。对一般曲线运动，把 R 换成轨迹该点的曲率半径 ρ 即可。")
d.image(FIG + "圆周运动加速度.png", 8, "图1-2  圆周运动的切向加速度和法向加速度")
d.p("用角量描述：角位置 θ(t)，角速度 ω = dθ/dt，角加速度 α = dω/dt。角量与线量的关系为 v = Rω，aₜ = Rα，aₙ = Rω² = v²/R。")
d.example("【例1-3】", "质点沿半径 R = 0.10 m 的圆周运动，角位置 θ = 2 + 4t³（rad）。求 t = 2 s 时的切向加速度和法向加速度。", [
    "ω = dθ/dt = 12t²，α = dω/dt = 24t。t = 2 s 时 ω = 48 rad/s，α = 48 rad/s²。",
    "aₜ = Rα = 0.10 × 48 = 4.8 m/s²，aₙ = Rω² = 0.10 × 48² ≈ 230 m/s²。",
])
d.h("1.5  相对运动")
d.p("同一质点在两个相对平动的参考系中的速度满足伽利略速度变换（低速情况下成立）：")
d.eq("v_AC = v_AB + v_BC")
d.p("读作：A 相对 C 的速度等于 A 相对 B 的速度加上 B 相对 C 的速度。例如在无风的雨天，雨滴竖直下落，而坐在行驶汽车中的人看到雨滴斜向后落下。")
d.h("本章小结")
d.bullets([
    "求导链：r(t) → v = dr/dt → a = dv/dt；积分链：a → v → r，需要初始条件。",
    "|Δr| ≠ Δs，但 |dr| = ds；速率是 ds/dt 而不是 d|r|/dt。",
    "抛体运动：水平匀速 + 竖直匀加速；R = v₀² sin2θ / g。",
    "圆周运动：aₜ = dv/dt 改变快慢，aₙ = v²/R 改变方向。",
    "相对运动：v_AC = v_AB + v_BC。",
])
