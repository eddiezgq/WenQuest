d = Doc()
d.title("实验一  单摆法测定重力加速度", "大学物理实验  ·  学时：2  ·  实验室：理科楼 305")
d.h("一、实验目的")
d.bullets(["学会用单摆测定当地的重力加速度。", "掌握用秒表测量周期时减小误差的方法（多周期累积测量）。", "学习用作图法（T²–L 图）处理数据。"], numbered=True)
d.h("二、实验原理")
d.p("质量可以忽略的细线下端悬挂一个小球，构成单摆。当摆角很小（θ < 5°）时，单摆近似做简谐振动，周期为")
d.eq("T = 2π √(L / g)")
d.p("其中 L 为摆长（悬点到小球球心的距离）。由此得 g = 4π² L / T²。改变摆长测出一组 (L, T)，以 T² 为纵坐标、L 为横坐标作图，得到一条过原点的直线，斜率 k = 4π²/g，于是 g = 4π²/k。")
d.image(FIG + "单摆示意.png", 5.5, "图1  单摆示意图")
d.h("三、实验仪器")
d.p("单摆装置（带刻度的支架）、小钢球、细线、米尺（分度值 1 mm）、游标卡尺、电子秒表（分度值 0.01 s）。")
d.h("四、实验步骤")
d.bullets([
    "用游标卡尺测量小球直径 d，用米尺测量悬点到小球顶端的线长 l，摆长 L = l + d/2。",
    "把小球拉离平衡位置，使摆角小于 5°，由静止释放。",
    "待摆动稳定后，从小球经过平衡位置时开始计时，测量连续 30 次全振动的时间 t，周期 T = t/30。每个摆长重复测量 3 次。",
    "改变摆长（约 50、60、70、80、90、100 cm），重复上述测量。",
    "把数据填入《单摆实验数据记录表》，计算各摆长下的 g，并作 T²–L 图求 g。",
], numbered=True)
d.h("五、注意事项")
d.bullets(["摆角必须小于 5°，否则周期公式误差增大。", "小球应在竖直平面内摆动，不能形成圆锥摆。", "从平衡位置开始计时，因为小球在平衡位置速度最大，计时误差最小。"])
d.h("六、思考题")
d.bullets(["为什么测量 30 个周期而不是 1 个周期？",
           "若把摆线长度当作摆长（忘记加小球半径），用作图法得到的 g 会偏大还是偏小？为什么？",
           "当地重力加速度的参考值约为 9.79 m/s²，分析你的结果与参考值偏差的主要来源。"], numbered=True)
