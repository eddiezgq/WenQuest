"""算例 10.2.1—10.2.3：线程束 64 道意味着什么（10.2 节）。

AMD 的 CDNA 架构里一个波前（wavefront）有 64 道，NVIDIA 的线程束固定 32 道。移植 CUDA 程序时，凡是把 32 写死的地方都要改。
本程序把第 4、5 章里受影响的三件事算清楚：
（1）线程束内归约的层数与每个线程块要用的共享内存（程序 5.2.1 的 v5）：32 道 5 层，64 道 6 层；
    每个线程块的线程数相同时，波前数只有线程束数的一半，存放部分和的共享内存也减半。
（2）合并访问：一条访存指令一次请求的字节数（第 4 章）。32 道 × 4 字节 = 128 字节，正好是一个缓存行；
    64 道 × 4 字节 = 256 字节。按 128 字节对齐、步长 128 字节的写法（算例 4.6.1）在 64 道上会落到两个 256 字节的请求里。
（3）占用率：共享内存（AMD 叫本地数据共享 LDS）限制每个计算单元能驻留几个线程块。
    CDNA 3（MI300X）每个计算单元 64 KB，与 A10 的每个 SM 100 KB 不同；CDNA 4（MI355X）增加到 160 KB。
    分块矩阵乘法（程序 5.7.1 的 tiled，每块 32×32×2 个单精度数 = 8 KB）在三者上各能驻留几块。

这三件事都只要算术，不需要 AMD 的卡：移植前先算一遍，知道哪些写法必须改。
"""
import math

from _ch10 import WARP
from bookout import out

B = 256                                             # 每个线程块的线程数（与程序 5.2.1 相同）
v = {}

# ---------- （1）线程束内归约
for name, w in WARP.items():
    key = "n" if w == 32 else "a"
    v[key + "_w"] = w
    v[key + "_steps"] = int(math.log2(w))           # 洗牌的层数
    v[key + "_groups"] = -(-B // w)                 # 一个线程块里的线程束/波前数（向上取整）= 要暂存的部分和个数
    v[key + "_smem"] = -(-B // w) * 4               # 存部分和的共享内存（字节）
    v[key + "_mask_bits"] = w                       # 掩码要覆盖的道数：32 道用 0xffffffff，64 道要 64 位掩码
    v[key + "_req"] = w * 4                         # 一条 32 位访存指令一次请求的字节数
v["lines_n"] = v["n_req"] / 128                     # 占几个 128 字节的缓存行
v["lines_a"] = v["a_req"] / 128

# 把为 32 道写的 v5 直接搬到 64 道上会错在哪里：
# 洗牌只做到 off = 16，每个波前里只有低 32 道与高 32 道各自求出一个和，0 号线程拿到的只是前一半的和。
v["bug_frac"] = 0.5                                 # 结果约为正确值的一半（各波前的高 32 道被丢掉）
v["fix_steps"] = int(math.log2(WARP["AMD CDNA"]))   # 改法：循环从 w/2 开始，w 取 warpSize

# ---------- （3）占用率：共享内存限制的驻留线程块数
TILE_SMEM = 2 * 32 * 32 * 4                         # tiled 版每块的共享内存：As 与 Bs 各 32×32 个单精度数
SMEM = {"a10": 100 * 1024, "cdna3": 64 * 1024, "cdna4": 160 * 1024}   # 每个 SM / 每个计算单元可用的共享内存
for k, s in SMEM.items():
    v["tile_" + k] = s // TILE_SMEM                 # 能驻留几个线程块
v["tile_KB"] = TILE_SMEM / 1024
# 注意：共享内存只是其中一道限制。tiled 版每块 32×32 = 1024 个线程，A10 每个 SM 最多驻留 1536 个线程（3.7 节），
# 所以在 A10 上真正的限制是线程数，只能驻留 1 块；共享内存允许的块数（上面算出的）要大得多。
# 本算例只比较“共享内存这一道限制”在三者上的差别，不下占用率的结论——占用率要把各道限制一起看（算例 5.7.2）。
v["tile_a10_threads"] = 1536 // (32 * 32)

# 32×32 的块在 64 道的波前上怎样排：一个 32×32 的线程块有 1024 个线程 = 16 个波前（32 道时 32 个线程束）。
v["tile_waves_a"] = 32 * 32 // 64
v["tile_waves_n"] = 32 * 32 // 32

out(**v)
