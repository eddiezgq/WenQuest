"""算例 11.5.1—11.5.3：三维视觉的三笔账（11.5 节）。

（1）深度图到点云：针孔相机模型 X = (u − c_x)·Z / f_x、Y = (v − c_y)·Z / f_y。一帧 1280×720 的深度图有多少个点、
    多少字节；按 30 帧每秒是多少带宽——与第 3 章的显存带宽对照，就知道点云为什么要先下采样。
（2）体素与点：把 1 立方米的空间按 5 毫米的体素离散要多少个格子（绝大多数是空的），
    与一个几十万点的点云对照——这是点云方法不用体素的原因。
（3）神经辐射场与三维高斯泼溅的代价：前者每条光线要采样几十个点、每个点过一遍小网络，
    渲染一张图要多少次网络前向；后者把场景表示成若干个带颜色与协方差的高斯球，渲染是光栅化。
    两者在“一张图要多少次运算”上差几个数量级——这是后者能实时的原因。
"""
import numpy as np

from bookout import out
from gpus import GPUS

v = {}
# ---------- （1）深度图到点云
W, H, FPS = 1280, 720, 30
fx = fy = 900.0                                   # 焦距（像素）
cx, cy = W / 2, H / 2
v["W"], v["H"], v["fps"] = W, H, FPS
v["pts"] = W * H
v["pc_MB"] = W * H * 3 * 4 / 1e6                  # 每点三个单精度坐标
v["pc_GBs"] = W * H * 3 * 4 * FPS / 1e9
v["a10_bw_GBs"] = GPUS["a10"]["bw"] / 1e9
# 核对一个点：深度 1.5 m 处的像素 (u, v) = (1000, 500)
u, vv, Z = 1000, 500, 1.5
X, Y = (u - cx) * Z / fx, (vv - cy) * Z / fy
v["X"], v["Y"], v["Z"] = X, Y, Z
v["r"] = float(np.sqrt(X * X + Y * Y + Z * Z))
# 一个像素在 1.5 m 处代表多大（横向分辨率）
v["px_mm"] = Z / fx * 1000

# ---------- （2）体素与点
SIDE, VOX = 1.0, 0.005                            # 1 立方米、5 毫米的体素
n = int(SIDE / VOX)
v["vox_side"] = n
v["vox_total"] = n ** 3
v["vox_total_M"] = n ** 3 / 1e6
v["vox_bytes_MB"] = n ** 3 * 4 / 1e6              # 每个体素存一个单精度数
# 只有表面上的体素是有内容的：一个 0.3 m 见方的零件表面约占多少个体素
surf = 6 * (0.3 / VOX) ** 2
v["vox_surface"] = int(surf)
v["vox_fill_pct"] = surf / n ** 3 * 100

# ---------- （3）辐射场与高斯泼溅
# 每像素一条光线；原论文用分层采样（粗网络 64 个点 + 细网络 128 个点），这里只算其中一次 64 点采样，
# 实际约为此三倍——结论（比光栅化慢几个数量级）不受影响
RAYS, SAMPLES = W * H, 64
MLP = 8 * 256 * 256 * 2                           # 小网络一次前向的运算量（8 层、宽 256，一次乘加算两次）
v["nerf_fwd"] = RAYS * SAMPLES
v["nerf_GF"] = RAYS * SAMPLES * MLP / 1e9
v["nerf_fps_A10"] = GPUS["a10"]["fp16t"] / (RAYS * SAMPLES * MLP)   # A10 半精度峰值下的理论帧率（全部用上才有这么快）
GAUSS = 1_000_000                                 # 一个场景约一百万个高斯球
PROJ = 100                                        # 每个高斯球投影到屏幕上的运算量（量级估计）
OVERLAP, PER_PIX = 64, 30                         # 每个像素平均被几十个高斯球覆盖，每次混合几十次运算
v["gs_n"] = GAUSS
v["gs_GF"] = (GAUSS * PROJ + W * H * OVERLAP * PER_PIX) / 1e9
v["ratio"] = v["nerf_GF"] / v["gs_GF"]
# 两者的运算量差几个数量级；但高斯泼溅实际跑不到“峰值 ÷ 运算量”那么快——它的瓶颈是按深度排序与读写，
# 计算强度很低（第 3 章的屋顶线：落在带宽那一边）。书中因此只比较运算量的量级，不把理论帧率当成实测。
# 每个高斯球存 59 个单精度数（3 位置 + 3 缩放 + 4 旋转 + 1 不透明度 + 48 个球谐系数），每个像素读写 4 个数
v["gs_arith_int"] = v["gs_GF"] * 1e9 / (GAUSS * (59 * 4) + W * H * 4 * 4)   # 粗估的计算强度（FLOP/B）
out(**v)
