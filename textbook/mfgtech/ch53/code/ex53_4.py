"""53.4 节：基准不重合时工序尺寸的换算。
算例 53.4.1 定位基准不重合（第 51 章算例 51.6.1 的继续）：以右端面定位车齿轮位左轴肩 S2（52 由图纸的 40 + 12 推得），求工序尺寸；
算例 53.4.2 测量基准不重合：轴套的内台阶深度不好测，改从外端面测量，求测量尺寸，并分析“假废品”。"""
import _mfg as M
from bookout import out

TL = M.tol()
L = M.link
# 53.4.1（接第 51 章算例 51.6.1）：齿轮位左轴肩 S2 到左端面的设计尺寸 52（40 + 12，GB/T 1804-m ±0.3），若以右端面 R 为工序基准
# （尺寸 R→S2 = A），联系尺寸是总长 L–R = 167 ± 0.2（工序 40 控制）。封闭环：52 = 167 − A → A = 115，A 为减环
A = TL.solve_link([L("总长 167", 167, 0.2, -0.2, +1)], (52, 0.3, -0.3), "A（R→S2）", -1)
# 若总长只按 ±0.5（图纸）控制
try:
    TL.solve_link([L("总长 167", 167, 0.5, -0.5, +1)], (52, 0.3, -0.3), "A", -1)
    loose = "有解"
except ValueError:
    loose = "无解"
# 53.4.2：轴套总长 A1 = 50（0/−0.17），内台阶深度（从内端面到台阶）A0 = 10（0/−0.36）是设计尺寸，测量时改测外端面到台阶的距离 A2：
# A0 = A1 − A2 → A2 = A1 − A0，A2 为减环
A2 = TL.solve_link([L("总长 A1", 50, 0, -0.17, +1)], (10, 0, -0.36), "A2", -1)
# 假废品：某件实测 A2 = 40.30（超出换算后的上限，判为不合格），而它的总长实测 50.00（A1 的上限），A0 = 50.00 − 40.30
a2_meas, a1_meas = 40.30, 50.00
a0 = a1_meas - a2_meas
good = 10 - 0.36 <= a0 <= 10
# 只要 A1 在公差内，A2 落在 [A1min − A0max, A1max − A0min] 之内的工件都可能是好的
rng_lo, rng_hi = (50 - 0.17) - 10, 50 - (10 - 0.36)
# 换算后测量尺寸的公差比设计公差小：T(A2) = T0 − T1
out(A_nom=A.nominal, A_es=A.es, A_ei=A.ei, A_T=A.T, loose=loose, A2_nom=A2.nominal, A2_es=A2.es, A2_ei=A2.ei, A2_T=A2.T,
    A2_min=A2.min, A2_max=A2.max, a2_meas=a2_meas, a1_meas=a1_meas, a0=a0, good="合格" if good else "不合格",
    range_lo=rng_lo, range_hi=rng_hi)
