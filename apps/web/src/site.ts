// Who runs this platform (round 48). On the China server (WQ_REGION=cn) the gateway reports the brand, company and
// filing numbers: the platform then shows them in a footer, labels AI output “AI 生成”, and words course access as
// “申请 / 开通” instead of enrolment and prices (the company teaches no paid classes to individuals).
// Elsewhere the answer is just { region: "us" } and nothing changes.
import { computed, ref } from "vue";
import { request } from "./api";
import { setRegionOverrides } from "./i18n";

export interface SiteInfo {
  region: "us" | "cn";
  brand?: string; company?: string; icp?: string; psb?: string; ai_reg?: string; ai_model?: string; ai_label?: boolean; signup?: boolean;
}

export const site = ref<SiteInfo>({ region: "us" });
export const isCN = computed(() => site.value.region === "cn");

let loading: Promise<void> | null = null;

export function loadSite(): Promise<void> {
  if (!loading) {
    loading = request<SiteInfo>("GET", "/api/v1/public/site")
      .then((s) => {
        site.value = s && s.region === "cn" ? s : { region: "us" };
        if (isCN.value) setRegionOverrides(cnText(site.value.brand || "问渠科技"));
      })
      .catch(() => { loading = null; });
  }
  return loading;
}

