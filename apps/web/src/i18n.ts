const KEY = "wq.locale";

function initial(): Locale {
  try {
    const saved = uni.getStorageSync(KEY);
    if (saved === "zh" || saved === "en") return saved;
    const sys = (uni.getSystemInfoSync().language || "").toLowerCase();
    return sys.startsWith("zh") ? "zh" : "en";
  } catch {
    return "zh";
  }
}

export const locale = ref<Locale>(initial());

export function setLocale(l: Locale) {
  locale.value = l;
  try {
    uni.setStorageSync(KEY, l);
  } catch {
    /* storage may be unavailable */
  }
}

export function toggleLocale() {
  setLocale(locale.value === "zh" ? "en" : "zh");
}

export function t(key: string, vars: Record<string, string | number> = {}): string {
  const s = messages[locale.value][key] ?? messages.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

export function errorText(code: string): string {
  const key = `error.${code}`;
  if (messages[locale.value][key]) return t(key);
  // Unmapped codes still tell the teacher (and us) what happened, e.g. "出错了（http_502）".
  return code && code !== "unknown" ? `${t("error.unknown")}（${code}）` : t("error.unknown");
}

export function formatDate(ts: number | null | undefined): string {
  if (!ts) return "";
  const d = new Date(ts * 1000);
  const pad = (n: number) => String(n).padStart(2, "0");
  const date = `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
  return `${date} ${pad(d.getHours())}:${pad(d.getMinutes())}`;
}

