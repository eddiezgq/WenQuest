# 尺寸段上限（mm）：3…6, 6…10, 10…18, 18…30, 30…50
SEG = [6, 10, 18, 30, 50]
IT = {5: [5, 6, 8, 9, 11], 6: [8, 9, 11, 13, 16], 7: [12, 15, 18, 21, 25], 9: [30, 36, 43, 52, 62]}
# 轴的基本偏差（μm）：f g 为上偏差 es；k p r 为下偏差 ei；h 为 0；js 对称
SHAFT = {"f": [-10, -13, -16, -20, -25], "g": [-4, -5, -6, -7, -9],
         "k": [1, 1, 1, 2, 2], "p": [12, 15, 18, 22, 26], "r": [15, 19, 23, 28, 34]}
# 孔的基本偏差（μm）：F G 为下偏差 EI；R 为上偏差 ES（IT7 及以上直接查表值）
HOLE_EI = {"F": [10, 13, 16, 20, 25], "G": [4, 5, 6, 7, 9]}
HOLE_R7_ES = [-11, -13, -16, -20, -25]
# 滚动轴承普通级：外圈外径 D、内圈内径 d 的偏差（上 0，下 …）
BRG_D = [-8, -8, -8, -9, -11]
BRG_d = [-8, -8, -8, -10, -12]


def seg(d):
    for i, u in enumerate(SEG):
        if d <= u:
            return i
    raise ValueError(d)


def hole(d, z):
    """孔公差带 → (下偏差, 上偏差) μm"""
    i, letter, g = seg(d), z[0], int(z[1:])
    if letter == "H":
        return 0, IT[g][i]
    if letter in HOLE_EI:
        return HOLE_EI[letter][i], HOLE_EI[letter][i] + IT[g][i]
    if z == "R7":
        return HOLE_R7_ES[i] - IT[7][i], HOLE_R7_ES[i]
    raise ValueError(z)


def shaft(d, z):
    """轴公差带 → (下偏差, 上偏差) μm；'brgD' 'brgd' 为轴承外圈、内圈"""
    i = seg(d)
    if z == "brgD":
        return BRG_D[i], 0
    if z == "brgd":
        return BRG_d[i], 0
    letter, g = z[:-1], int(z[-1])
    if letter == "h":
        return -IT[g][i], 0
    if letter == "js":
        return -IT[g][i] / 2, IT[g][i] / 2
    if letter in ("f", "g"):
        return SHAFT[letter][i] - IT[g][i], SHAFT[letter][i]
    if letter in ("k", "p", "r"):
        return SHAFT[letter][i], SHAFT[letter][i] + IT[g][i]
    raise ValueError(z)


def fit(d, hz, sz, hole_is_bearing_bore=False):
    """返回 (最小间隙, 最大间隙) μm，负数为过盈。hole_is_bearing_bore：孔是轴承内圈（内径按 P0）"""
    hl, hu = ((BRG_d[seg(d)], 0) if hole_is_bearing_bore else hole(d, hz))
    sl, su = shaft(d, sz)
    return hl - su, hu - sl


def kind(lo, hi):
    if lo >= 0:
        return "间隙"
    if hi <= 0:
        return "过盈"
    return "过渡"


