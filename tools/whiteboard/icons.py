"""白板简笔画图标（200×200 坐标，只用绝对坐标的 M L C Q A Z）。每个图标是几笔，按顺序一笔一笔画。
都是本项目自己画的线稿，可随意使用。"""
import math


def circle(cx, cy, r):
    return f"M{cx - r},{cy} A{r},{r} 0 1 1 {cx + r},{cy} A{r},{r} 0 1 1 {cx - r},{cy}"


def ellipse(cx, cy, rx, ry, rot=0):
    a = math.radians(rot)
    dx, dy = rx * math.cos(a), rx * math.sin(a)
    return f"M{cx - dx:.1f},{cy - dy:.1f} A{rx},{ry} {rot} 1 1 {cx + dx:.1f},{cy + dy:.1f} A{rx},{ry} {rot} 1 1 {cx - dx:.1f},{cy - dy:.1f}"


def rays(cx, cy, r1, r2, n, start=0):
    out = []
    for i in range(n):
        a = math.radians(start + 360 * i / n)
        out.append(f"M{cx + r1 * math.cos(a):.1f},{cy + r1 * math.sin(a):.1f} L{cx + r2 * math.cos(a):.1f},{cy + r2 * math.sin(a):.1f}")
    return out


def gear(cx, cy, r, teeth=8, depth=14):
    pts = []
    for i in range(teeth * 4):
        a = 2 * math.pi * i / (teeth * 4)
        rr = r + (depth if i % 4 in (1, 2) else 0)
        pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
    return "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + " Z"


def lattice():
    out = []
    for i in range(4):
        out.append(f"M30,{40 + i * 40} L170,{40 + i * 40}")
        out.append(f"M{40 + i * 40},30 L{40 + i * 40},170")
    for i in range(4):
        for j in range(4):
            out.append(circle(40 + i * 40, 40 + j * 40, 9))
    return out


