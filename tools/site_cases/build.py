def main():
    preview_dir = None
    if "--preview" in sys.argv:
        preview_dir = pathlib.Path(sys.argv[sys.argv.index("--preview") + 1])
        preview_dir.mkdir(parents=True, exist_ok=True)
    OUT.mkdir(parents=True, exist_ok=True)
    shutil.copy(HERE / "assets" / "three.min.js", OUT / "three.min.js")
    (OUT / "index.html").write_text(index(False), encoding="utf-8")
    for c in CASES:
        (OUT / f"{c['slug']}.html").write_text(page(c, False), encoding="utf-8")
        if preview_dir:
            (preview_dir / f"{c['slug']}.html").write_text(page(c, True), encoding="utf-8")
    if preview_dir:
        (preview_dir / "index.html").write_text(index(True), encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
