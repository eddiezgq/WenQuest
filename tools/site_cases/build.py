    parts = [{"id": pid, "label": list(lbl), "cap": list(cap)} for pid, lbl, cap in case["parts"]]
    facts = "".join(f'<div><dt>{bi(lbl)}</dt><dd>{v}<small>{u}</small></dd></div>' for lbl, v, u in case["facts"])
    tabs = "".join(
        f'<button type="button" data-part="{p["id"]}" aria-pressed="{"true" if i == 0 else "false"}">{bi(p["label"])}</button>'
        for i, p in enumerate(parts))
    opens = "".join(f"<div><h4>{bi(h)}</h4><p>{bi(t)}</p></div>" for h, t in case["open"])
    courses = "".join(f"<li><span><b>{bi(n)}</b><small>{bi(d)}</small></span><em>{bi(s)}</em></li>" for n, d, s in case["courses"])
    labs = "".join(f'<li><b>{bi((a, c))}</b>{bi(("：" + b, ": " + d))}</li>' for a, b, c, d in case["labs"])
