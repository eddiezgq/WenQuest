import base64
import html
import json
import pathlib
import re
import shutil
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "site" / "cases"
sys.path.insert(0, str(HERE))
from cases import CASES, REPO  # noqa: E402

CDN_THREE = "https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js"


def bi(pair, tag="span"):
    zh, en = pair
    return f"<{tag} data-zh>{zh}</{tag}><{tag} data-en>{en}</{tag}>"


def layout_img(slug):
    p = HERE / "assets" / f"{slug}.layout.png"
    if not p.exists():
        return None
    return "data:image/png;base64," + base64.b64encode(p.read_bytes()).decode()


def resolve(case, side, lang):
    if side == "@layout":
        src = layout_img(case["slug"])
        cap = ("布局轴测图（FreeCAD 1.0.2 自动生成）", "Layout, isometric (generated by FreeCAD 1.0.2)")[lang]
        alt = ("关节布局：电机、谐波减速器与驱动器的轴测图", "Joint layout: motor, harmonic reducer and drive")[lang]
        return f'<figure class="fig"><img src="{src}" alt="{alt}"><figcaption>{cap}</figcaption></figure>' if src else ""
    if side == "@gcode":
        return f"<pre>{html.escape(case['gcode'])}</pre>"
    return side


def steps_json(case):
    out = []
    for lane, key in ((0, "design"), (1, "factory")):
        for i, st in enumerate(case[key]):
            out.append({
                "n": len(out) + 1, "lane": lane, "s": st["s"],
                "t": list(st["t"]), "who": list(st["who"]),
                "body": list(st["body"]),
                "side": [resolve(case, st["side"][0], 0), resolve(case, st["side"][1], 1)],
            })
    return out


STYLE = (HERE / "style.css").read_text(encoding="utf-8")
SCRIPT = (HERE / "page.js").read_text(encoding="utf-8")


