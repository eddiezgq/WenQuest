"""第 4 轮 · 第 3 步：上篇教学评价指标目录。每个指标都必须写明定义、来源、时点、最小样本、可见范围。"""
import json
V_T, V_C, V_D, V_P = "教师本人", "课程负责人", "院系汇总", "对外公开"
I = []
def add(id, area, name, formula, source, when, min_n, visible, push=None, overview=False, note=""):
    I.append(dict(编号=id, 方面=area, 名称=name, 定义与公式=formula, 数据来源=source, 统计时点=when,
                  最小样本=min_n, 可见范围=visible, 推送校情中枢=push, 进入概览=overview, 解读注意=note))
Q, P, O, F, A = "课程质量", "教学过程", "学习成效", "学生反馈", "平台AI"
add("Q1", Q, "目标覆盖率", "有考核环节对应的课程目标数 ÷ 课程目标总数", "课程目标、目标-考核映射", "建课时、每学期初", "—", [V_T, V_C], overview=True, note="低于 100% 说明有目标没考")
add("Q2", Q, "考核对齐率", "能对应到课程目标的考核项数 ÷ 考核项总数", "题目模板、实验、量规、目标-考核映射", "建课时、每学期初", "—", [V_T, V_C], note="没有目标的考核项要么补目标、要么删掉")
add("Q3", Q, "内容复算差错", "程序复算与课件、题目中数值不一致的条数（理工科）", "内容审核记录", "建课时、内容修改后", "—", [V_T, V_C], overview=True, note="逐条列出，附原文位置和复算值")
add("Q4", Q, "中英文不一致", "中英两版在数值、术语、结论上不一致的条数", "内容审核记录", "建课时、内容修改后", "—", [V_T, V_C])
add("Q5", Q, "问题题目比例", "难度 <0.20 或 >0.95、区分度 <0.20、或高分组正确率低于低分组的题目数 ÷ 已统计题目数", "作答、题目统计", "每次考试后", "每题 ≥30 人作答", [V_T, V_C], overview=True, note="高分组反而答错，常常是答案或题干有错，优先核查")
add("Q6", Q, "同行评议意见", "同行按统一量规写的意见（文字）", "同行评议记录", "教师邀请时", "—", [V_T], note="可选，不计入任何数值")
add("P1", P, "答疑响应时长", "学生提问到教师或助教首次有效回复的时长中位数（只计工作时间）", "答疑记录", "每周、学期末", "≥10 次提问", [V_T], overview=True, note="AI 助教已答且学生未追问的不计入")
add("P2", P, "批改周期", "作业提交截止到成绩和反馈发布的天数中位数", "批改记录", "每次作业、学期末", "—", [V_T])
add("P3", P, "反馈具体度", "抽样反馈中同时指出具体错误和改进方法的比例（AI 初判，教师可申辩）", "批改记录（反馈文字）", "学期末", "抽样 ≥20 条", [V_T], note="只看是否具体，不看长短")
add("P4", P, "终审处理质量", "终审案例处理时长中位数；理由写清依据的比例", "教师复核记录（第 3 轮）", "学期末", "≥5 个案例", [V_T, V_C])
add("P5", P, "课堂互动", "互动时长 ÷ 课堂总时长；每课时提问次数；开放式提问比例", "课堂分析（须教师开启，H5）", "每次开启分析的课后", "—", [V_T], note="默认关闭；只保留统计结果")
add("O1", O, "掌握度增值", "期末平均掌握概率 − 期初诊断平均掌握概率（可细到知识点）", "掌握度（第 3 轮）", "学期末", "≥15 人", [V_T, V_D], push="learning_gain", overview=True, note="看进步，不看绝对分；与往届、同类课程比较时考虑起点")
add("O2", O, "知识点卡点", "期末掌握率低于 50% 的知识点列表，并关联到对应的讲次和实验", "掌握度、课程结构", "学期中每周、学期末", "≥15 人", [V_T, V_C], overview=True)
add("O3", O, "课程目标达成度", "第 4 轮第 1 步方法（K1–K4）", "作答、过程、报告、答辩", "学期末", "—", [V_T, V_C, V_D], push="course_objective_attainment", overview=True)
add("O4", O, "独立理解", "答辩“独立理解”一项的全班平均分和分布", "答辩（第 3 轮）", "答辩结束后", "≥10 人", [V_T, V_C])
add("O5", O, "预警干预效果", "被预警学生在干预后 4 周内信号解除的比例", "学业预警、掌握度", "学期末", "≥5 人被预警", [V_T])
add("F1", F, "期中反馈", "期中 3–5 题问卷的结果和留言主题", "评教回答", "学期过半", "≥5 份", [V_T], note="只给教师本人（H3），不推送")
add("F2", F, "期末行为题得分", "每道行为题的平均分（1–5）和分布", "评教回答", "成绩发布后可见", "≥5 份", [V_T, V_D], note="院系只看汇总，不看个人（H1）")
add("F3", F, "留言主题", "期末留言按主题归类的条数和代表性原话（隐去身份，过滤辱骂）", "评教回答", "成绩发布后可见", "≥5 份", [V_T, V_D], push="feedback_themes", overview=True)
add("F4", F, "评教与成效对照", "评教得分与掌握度增值不一致时提示，例如评教低而增值高", "F2、O1", "学期末", "两项都满足最小样本", [V_T], note="提醒教师别只看评教，也别只看分数")
add("A1", A, "助教准确率", "教师抽检的助教回答中正确的比例", "AI 质量抽检", "每月", "抽检 ≥20 条", [V_T, V_P], note="架构说明书目标 ≥90%")
add("A2", A, "助教无帮助率", "学生标记“没帮助”的回答 ÷ 助教回答总数", "答疑记录", "每周", "≥50 次回答", [V_T])
add("A3", A, "批改一致性", "AI 建议分与教师终审分相差在满分 10% 以内的比例", "评分、教师复核", "每次作业", "≥20 份", [V_T, V_P], note="架构说明书目标 ≥80%")
add("A4", A, "答辩组可靠性", "被申诉改判的比例；评委共同误判的次数（参见第 3 轮第 5 步 P01）", "答辩、教师复核", "学期末", "≥10 场", [V_T, V_P])
add("A5", A, "自适应补测变动", "补测后掌握档位发生变化的知识点比例", "掌握度", "学期末", "≥30 人次", [V_T])

REQ = ["编号", "方面", "名称", "定义与公式", "数据来源", "统计时点", "最小样本", "可见范围"]
assert all(all(x[k] for k in REQ) for x in I), "有指标缺项"
assert len({x["编号"] for x in I}) == len(I)
for x in I:   # 边界检查：教师过程类、期中反馈不得出教师本人以外；推送项必须对得上契约类型
    if x["方面"] == P or x["编号"] == "F1": assert set(x["可见范围"]) <= {V_T, V_C}, x["编号"]
    if x["推送校情中枢"]: assert x["推送校情中枢"] in {"learning_gain", "course_objective_attainment", "feedback_themes"}
json.dump(I, open("indicators_v1.json", "w"), ensure_ascii=False, indent=1)
print(len(I), "个指标，检查通过；进入概览：", [x["编号"] for x in I if x["进入概览"]])
